package Abstraction;

public class cat implements Animal {
	
	public void sound() {
		System.out.println("cat sounds like Meow..meow..");
	}
	public void eat() {
		System.out.println("cat eat rat");
	}
	public void walk() {
		System.out.println("cat can walk and jump");
	}
	public void display() {
		System.out.println("Hi");
	}
}
